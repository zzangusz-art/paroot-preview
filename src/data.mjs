const RANK = { on: 0, soon: 1, always: 2, notice: 3, closed: 4 };
export const sortedNotices = () => [...NOTICES].sort((a, b) => RANK[noticeStatus(a).key] - RANK[noticeStatus(b).key] || b.date.localeCompare(a.date));

